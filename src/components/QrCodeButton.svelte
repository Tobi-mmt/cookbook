<script lang="ts">
	import QrCode from '@lucide/svelte/icons/qr-code';
	import X from '@lucide/svelte/icons/x';

	let { url, label }: { url: string; label: string } = $props();

	let dialog = $state<HTMLDialogElement>();
	let svg = $state('');

	const open = async () => {
		const { renderSVG } = await import('uqr');
		svg = renderSVG(url, { border: 1 });
		dialog?.showModal();
	};
</script>

<button type="button" class="btn" onclick={open}>
	<QrCode size="1.1em" aria-hidden="true" /> QR-Code anzeigen
</button>

<dialog bind:this={dialog} aria-label={label}>
	<form method="dialog" class="close">
		<button type="submit" class="btn btn--quiet" aria-label="Schließen"
			><X size="1.2em" aria-hidden="true" /></button
		>
	</form>
	<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by uqr from our own URL -->
	<div class="code">{@html svg}</div>
	<p>{url.replace(/^https?:\/\//, '')}</p>
</dialog>

