<script lang="ts">
	import QrCode from '@lucide/svelte/icons/qr-code';
	import Dialog from '#components/Dialog.svelte';

	let {
		url,
		label,
		compact = false
	}: {
		url: string;
		label: string;
		/** only the icon, e.g. next to a name */ compact?: boolean;
	} = $props();

	let open = $state(false);
	let svg = $state('');

	const show = async () => {
		const { renderSVG } = await import('uqr');
		svg = renderSVG(url, { border: 1 });
		open = true;
	};
</script>

{#if compact}
	<button type="button" class="icon" onclick={show} aria-label={label} title="QR-Code anzeigen">
		<QrCode size="1em" aria-hidden="true" />
	</button>
{:else}
	<button type="button" class="btn" onclick={show}>
		<QrCode size="1.1em" aria-hidden="true" /> QR-Code anzeigen
	</button>
{/if}

<Dialog bind:open title={label}>
	<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by uqr from our own URL -->
	<div class="code">{@html svg}</div>
	<p class="url">{url.replace(/^https?:\/\//, '')}</p>
</Dialog>

